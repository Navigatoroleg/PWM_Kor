#ifndef COIL_CONFIG_H
#define COIL_CONFIG_H

// Настройки расчёта расходомера — то же, что в окнах «Анализ катушек» и «Коэфф. прибора» Qt.
// Меняются здесь, после правки — пересобрать и прошить

// ---------------------------------------------------------------------------------------------
// Расход: K и ноль (Qt: «Массовый расход», «Коэфф. прибора…», «Разность фаз»)
// ---------------------------------------------------------------------------------------------

// Коэффициенты прибора с вкладки «Параметры» Shtray Link
#define COIL_METER_SCALE        22.28     // «Масштаб расхода», кг/мин на мкс
#define COIL_METER_ETHA         1.1       // «etha»
#define COIL_METER_K1           0.000426  // «K1», поправка масштаба на 1 °C
#define COIL_METER_TCAL_C       24.0      // «Температура калибровки», °C (в приборе записано ×100: 2400)
#define COIL_METER_T_C          (-200.0)  // температура трубки, °C. −200 — датчик в обрыве, как сейчас в приборе;
                                          // равна COIL_METER_TCAL_C — без температурной поправки

// K, кг/мин на мкс: масштаб × etha × (1 + K1·(Tкал − T)). Можно заменить готовым числом
#define COIL_K_KGMIN_PER_US     (COIL_METER_SCALE * COIL_METER_ETHA \
                                 * (1.0 + COIL_METER_K1 * (COIL_METER_TCAL_C - COIL_METER_T_C)))

// Ноль Δt, мкс: Δt при нулевом расходе, вычитается из показаний (Qt: «Обнулить» / «Задать…»)
#define COIL_ZERO_US            0.0

// Отсечка малого расхода, мкс: |Δt| меньше — расход 0 (Qt: «Отсечка»)
#define COIL_CUTOFF_US          0.5

// Единицы вывода расхода: множитель от кг/мин и подпись (Qt: «Единицы»)
// кг/мин — 1.0, "kg/min";  г/с — 1000.0/60.0, "g/s";  кг/ч — 60.0, "kg/h";  т/ч — 0.06, "t/h"
#define COIL_FLOW_UNIT_FACTOR   1.0
#define COIL_FLOW_UNIT_NAME     "kg/min"

// ---------------------------------------------------------------------------------------------
// Фильтрация (Qt: «Демпфирование», «Окно усреднения», «Фильтры»)
// ---------------------------------------------------------------------------------------------

// Демпфирование Δt, с: экспонента с шагом в блок 12,8 мс. 0 — без демпфирования (Qt: «Демпфирование»)
#define COIL_TAU_S              4.0

// Сглаживание частоты, полученной по набегу фазы, с
#define COIL_FREQ_TAU_S         1.0

// Окно подгонки синуса, периодов трубки (Qt: «Окно усреднения»). Ограничено 64…2048 точками
#define COIL_FIT_PERIODS        4.0f

// Гистерезис переходов К1 через уровень, доля полуразмаха (Qt: «гистерезис»)
#define COIL_HYST_FRACTION      0.2f

// ---------------------------------------------------------------------------------------------
// Проверка сигнала
// ---------------------------------------------------------------------------------------------

// Амплитуда К1 меньше, мВ, — колебаний нет (Qt: «Слабый сигнал»)
#define COIL_WEAK_MV            10.0

// Сигнал/шум ниже, дБ, на любом канале — это шум, а не трубка (Qt: «Шумный сигнал» при 20)
#define COIL_MIN_SNR_DB         10

// ---------------------------------------------------------------------------------------------
// Оцифровка
// ---------------------------------------------------------------------------------------------

// Частота точек после накопления, Гц, и кратность накопления. TIM2 = COIL_FS_HZ × COIL_OS,
// выставляется при запуске. COIL_OS не больше 16: точка хранится в 16 битах
#define COIL_FS_HZ              5000U
#define COIL_OS                 16U

// Опорное напряжение АЦП (VDDA), мВ. На Discovery около 3,0 В. Влияет только на амплитуды в мВ
#define COIL_VDDA_MV            3000.0

// ---------------------------------------------------------------------------------------------
// Вывод в порт
// ---------------------------------------------------------------------------------------------

// Период строки в USART2 / USB, мс. На расчёт не влияет
#define COIL_PRINT_MS           500U

#endif
